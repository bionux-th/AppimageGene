/// 末端类型。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Overhang {
    Blunt,
    FivePrime,
    ThreePrime,
    Iis,
}

impl Overhang {
    pub const fn label(self) -> &'static str {
        match self {
            Overhang::Blunt => "blunt",
            Overhang::FivePrime => "5' overhang",
            Overhang::ThreePrime => "3' overhang",
            Overhang::Iis => "type IIS",
        }
    }
}

/// 一条酶记录。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Enzyme {
    pub name: &'static str,
    pub site: &'static str,
    /// 正向链切点（相对位点 5′ 端；可负）。
    pub cut: i16,
    /// 从互补链位点的 5′ 端量起的切点；同一原点下底链为 site_len - reverse_cut。
    pub reverse_cut: i16,
    pub overhang: Overhang,
}

impl Enzyme {
    /// 识别序列长度（IUPAC 字符数）。
    #[inline]
    pub const fn site_len(&self) -> usize {
        self.site.len()
    }

    /// 是否为 IIS 型（切点在识别序列之外）。
    #[inline]
    pub const fn is_type_iis(&self) -> bool {
        matches!(self.overhang, Overhang::Iis)
    }
}

