/// 按名称精确查找（不区分大小写）。
pub fn by_name(name: &str) -> Option<&'static Enzyme> {
    ENZYMES.iter().find(|e| e.name.eq_ignore_ascii_case(name))
}

/// 常用酶集（与 SnapGene「常用」列表接近的 22 条）：UI 默认选择与 CLI 导出共用。
pub const COMMON: &[&str] = &[
    "EcoRI", "BamHI", "HindIII", "XhoI", "SalI", "PstI", "NotI", "XbaI", "KpnI", "SacI", "SphI",
    "NcoI", "NdeI", "BglII", "EcoRV", "SmaI", "SpeI", "NheI", "ApaI", "MluI", "ScaI", "StuI",
];

/// [`COMMON`] 在 [`ENZYMES`] 中的下标（升序去重，跳过库中不存在的名称）。
pub fn common_indices() -> Vec<usize> {
    let mut out: Vec<usize> = COMMON
        .iter()
        .filter_map(|n| ENZYMES.iter().position(|e| e.name.eq_ignore_ascii_case(n)))
        .collect();
    out.sort_unstable();
    out.dedup();
    out
}

/// 同一识别位点的**同切酶**里 SnapGene 偏好显示的名字。
///
/// 我们的酶表来自 REBASE（584 条），比 SnapGene 自带的酶表多出一些偏僻的
/// 同切酶；当若干酶识别同一序列（且同切点）时，SnapGene 显示的是下表里的名字。
/// 由 oracle 实拍裁定：
/// - pAd 34,864 bp：`ACTAGT`→SpeI、`TTCGAA`→BstBI、`GTTTAAAC`→PmeI、`GCGATCGC`→AsiSI；
/// - GFP 717 bp：`CCWGG`…`TGGCCA`→MscI、`RAATTY`→ApoI、`GGTNACC`→BstEII；
/// - pET160 5,839 bp：`GGTNACC`→BstEII、`RAATTY`→ApoI 等。
///
/// 未列出的名字仍按「短名优先、常用集次之」退化。
pub const PREFERRED: &[&str] = &[
    "ApoI", "AsiSI", "BstBI", "BstEII", "MscI", "PmeI", "SpeI",
];

/// [`PREFERRED`] 在 [`ENZYMES`] 中的下标集合。
pub fn preferred_indices() -> Vec<usize> {
    let mut out: Vec<usize> = PREFERRED
        .iter()
        .filter_map(|n| ENZYMES.iter().position(|e| e.name.eq_ignore_ascii_case(n)))
        .collect();
    out.sort_unstable();
    out.dedup();
    out
}

/// 全部「6 切点、非 IIS 型」酶的下标（SnapGene 默认显示集的近似）。
pub fn six_cutter_indices() -> Vec<usize> {
    ENZYMES
        .iter()
        .enumerate()
        .filter(|(_, e)| e.site_len() == 6 && !e.is_type_iis())
        .map(|(i, _)| i)
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_unique() {
        assert!(!ENZYMES.is_empty());
        for w in ENZYMES.windows(2) {
            assert!(w[0].name < w[1].name, "未按名称排序：{} / {}", w[0].name, w[1].name);
        }
    }

    #[test]
    fn sites_are_valid_iupac() {
        for e in ENZYMES {
            for &b in e.site.as_bytes() {
                assert!(
                    crate::iupac_bits(b).is_some(),
                    "{} 识别序列含非 IUPAC 字符：{:?}",
                    e.name,
                    e.site
                );
            }
        }
    }

    #[test]
    fn spot_checks() {
        let ecori = by_name("EcoRI").expect("EcoRI");
        assert_eq!(ecori.site, "GAATTC");
        assert_eq!((ecori.cut, ecori.reverse_cut), (1, 1));
        assert_eq!(ecori.overhang, Overhang::FivePrime);

        let smai = by_name("SmaI").expect("SmaI");
        assert_eq!(smai.site, "CCCGGG");
        assert_eq!(smai.overhang, Overhang::Blunt);

        let bsai = by_name("BsaI").expect("BsaI");
        assert_eq!(bsai.site, "GGTCTC");
        assert!(bsai.is_type_iis());
        assert_eq!((bsai.cut, bsai.reverse_cut), (7, -5));

        assert!(by_name("ecori").is_some(), "名称查找应不区分大小写");
        assert!(by_name("NotAnEnzyme").is_none());
    }
}
